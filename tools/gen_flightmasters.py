"""Generate CraftmansHelper/Data/FlightMasters.lua from QuestieDB (GPL-3.0).

    python tools/gen_flightmasters.py "<AddOns>/QuestieDB/QuestieDB_Forever.toc"

QuestieDB bakes its data into TOC metadata: "## X-Npc-<id>-<field>: base64 CBOR".
The "S" field is a map of scalar fields (1 = name, 13 = friendlyToFaction,
14 = subName, 15 = npcFlags); field 7 is spawns { [areaID] = { {x, y}, ... } }.
Flight masters are NPCs with the Classic FLIGHT_MASTER flag (8).
"""
import base64
import re
import struct
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "CraftmansHelper" / "Data" / "FlightMasters.lua"
FLIGHT_MASTER = 8

# Questie AreaID -> uiMapID (same table as CraftmansHelper/Questie.lua).
AREA_TO_MAP = {
    1: 1426, 3: 1418, 4: 1419, 8: 1435, 10: 1431, 11: 1437, 12: 1429, 14: 1411, 15: 1445, 16: 1447,
    17: 1413, 28: 1422, 33: 1434, 36: 1416, 38: 1432, 40: 1436, 41: 1430, 44: 1433, 45: 1417, 46: 1428,
    47: 1425, 51: 1427, 85: 1420, 130: 1421, 139: 1423, 141: 1438, 148: 1439, 215: 1412, 267: 1424,
    331: 1440, 357: 1444, 361: 1448, 400: 1441, 405: 1443, 406: 1442, 440: 1446, 490: 1449, 493: 1450,
    618: 1452, 1377: 1451, 1497: 1458, 1519: 1453, 1537: 1455, 1637: 1454, 1638: 1456, 1657: 1457,
    16591: 2548,
}
SKIP_NAME = re.compile(r"DEBUG|NYI|<PH>", re.I)
FLIGHT_TITLE = re.compile(r"^(Gryphon|Wind Rider|Hippogryph|Flight) Master$|^Bat Handler$")


def dec(b, i=0):
    ib = b[i]
    mt, ai = ib >> 5, ib & 31
    i += 1
    if ai < 24:
        v = ai
    elif ai == 24:
        v = b[i]; i += 1
    elif ai == 25:
        if mt == 7:
            return struct.unpack(">e", b[i:i + 2])[0], i + 2
        v = struct.unpack(">H", b[i:i + 2])[0]; i += 2
    elif ai == 26:
        if mt == 7:
            return struct.unpack(">f", b[i:i + 4])[0], i + 4
        v = struct.unpack(">I", b[i:i + 4])[0]; i += 4
    elif ai == 27:
        if mt == 7:
            return struct.unpack(">d", b[i:i + 8])[0], i + 8
        v = struct.unpack(">Q", b[i:i + 8])[0]; i += 8
    else:
        raise ValueError(f"unsupported CBOR additional info {ai}")
    if mt == 0:
        return v, i
    if mt == 1:
        return -1 - v, i
    if mt in (2, 3):
        return b[i:i + v], i + v
    if mt == 4:
        out = []
        for _ in range(v):
            x, i = dec(b, i); out.append(x)
        return out, i
    if mt == 5:
        out = {}
        for _ in range(v):
            k, i = dec(b, i); x, i = dec(b, i); out[k] = x
        return out, i
    if mt == 6:
        return dec(b, i)
    return {20: False, 21: True, 22: None}.get(v, v), i


def text(v):
    return v.decode("utf-8") if isinstance(v, bytes) else v


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(2)
    toc = Path(sys.argv[1]).read_text(encoding="utf-8")
    scalars = {int(m[1]): m[2] for m in re.finditer(r"^## X-Npc-(\d+)-S: (\S+)", toc, re.M)}
    spawns = {int(m[1]): m[2] for m in re.finditer(r"^## X-Npc-(\d+)-7: (\S+)", toc, re.M)}

    rows, skipped = [], []
    for npc, blob in sorted(scalars.items()):
        d = dec(base64.b64decode(blob))[0]
        if isinstance(d, list):
            d = {i + 1: v for i, v in enumerate(d)}
        flags = d.get(15)
        sub = text(d.get(14)) or ""
        # Some of Forever's new flight masters have no flags yet, only the title.
        if not ((isinstance(flags, int) and flags & FLIGHT_MASTER) or FLIGHT_TITLE.search(sub)):
            continue
        name = text(d.get(1)) or "?"
        if SKIP_NAME.search(name) or npc not in spawns:
            skipped.append(f"{npc} {name}: no spawn")
            continue
        sp = dec(base64.b64decode(spawns[npc]))[0]
        placed = None
        for area, points in sp.items():
            if area in AREA_TO_MAP and points and points[0][0] >= 0:
                placed = (AREA_TO_MAP[area], points[0][0], points[0][1])
                break
        if not placed:
            skipped.append(f"{npc} {name}: unmapped area {list(sp)}")
            continue
        fac = text(d.get(13)) or "AH"
        rows.append(f"    [{npc}] = {{ name = {lua_str(name)}, map = {placed[0]}, "
                    f"x = {placed[1]:.1f}, y = {placed[2]:.1f}, faction = \"{fac}\" }},")

    OUT.write_text(
        "-- Flight masters: generated by tools/gen_flightmasters.py from QuestieDB (GPL-3.0).\n"
        "-- [npcID] = { name, map = uiMapID, x, y (0-100), faction = \"A\" | \"H\" | \"AH\" }\n"
        "local _, ns = ...\n\n"
        "ns.FlightMasters = {\n" + "\n".join(rows) + "\n}\n",
        encoding="utf-8", newline="\n")
    print(f"wrote {len(rows)} flight masters to {OUT.name}")
    for s in skipped:
        print("skipped", s)


if __name__ == "__main__":
    main()
