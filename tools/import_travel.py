"""Import Glyalith's WoW Forever travel data (from EllesmereUI Forever Essentials) into the addon.

    python tools/import_travel.py "<AddOns>/EllesmereUIForeverEssentials"

Writes CraftmansHelper/Data/Transports.lua and CraftmansHelper/Data/FlightLengths.lua.
The data was collected by Glyalith and is used with permission, with credit (see README).

Transports come from MapTravelData.lua's `transports` table:
    [uiMapID] = { { x, y, kind, destination uiMapID, destination areaID }, ... }
Each entry is a one-way link from its dock to the destination map. The arrival dock is
the destination map's dock of the same kind that leads back here, else its first dock of
that kind (some boats sail a loop, e.g. Menethil -> Southshore -> Auberdine).

Flight lengths come from FlightTimerData.lua: flown yards per flight route, keyed
fromTaxiNodeID * 10000 + toTaxiNodeID.
"""
import re
import sys
from pathlib import Path

DATA = Path(__file__).resolve().parent.parent / "CraftmansHelper" / "Data"
CREDIT = ("-- Data collected by Glyalith for EllesmereUI Forever Essentials, used with permission.\n"
          "-- Generated by tools/import_travel.py; don't edit by hand.\n")


def parse_transports(text):
    block = text[text.index("transports = {"):]
    block = block[:block.index("\n    },")]
    docks = {}  # map -> [ (x, y, kind, dest) ]
    # Entries can span lines, so each dock belongs to the last "[map] =" seen before it.
    current = None
    for tok in re.finditer(r'\[(\d+)\] = \{|\{([\d.]+),([\d.]+),"(\w+)",(\d+),(\d+)\}', block):
        if tok[1]:
            current = int(tok[1])
        elif current is not None:
            docks.setdefault(current, []).append((float(tok[2]), float(tok[3]), tok[4], int(tok[5])))
    return docks


# Who can use a link ("faction" in the output): zeppelins are Horde, skycutters and the
# tram Alliance, and boats that call at an Alliance town are Alliance. Other boats
# (Ratchet - Booty Bay, Tanaris - the Riverglades) are neutral.
ALLIANCE_DOCKS = {
    1424,  # Hillsbrad Foothills (Southshore)
    1437,  # Wetlands (Menethil Harbor)
    1438,  # Teldrassil (Rut'theran Village)
    1439,  # Darkshore (Auberdine)
    1444,  # Feralas (Feathermoon ferry)
    1445,  # Dustwallow Marsh (Theramore)
    1453,  # Stormwind City
    1455,  # Ironforge
}


def link_faction(kind, src, dest):
    if kind == "zeppelin":
        return "H"
    if kind in ("skycutter", "tram") or src in ALLIANCE_DOCKS or dest in ALLIANCE_DOCKS:
        return "A"
    return None


def arrival(docks, src, x, y, kind, dest):
    # Never the dock you left from (the Feathermoon ferry has both ends on one map).
    candidates = [d for d in docks.get(dest, []) if d[2] == kind and (d[0], d[1]) != (x, y)]
    back = [d for d in candidates if d[3] == src]
    pick = (back or candidates or [None])[0]
    return pick


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(2)
    root = Path(sys.argv[1])
    travel = (root / "EllesmereUIForeverEssentials_MapTravelData.lua").read_text(encoding="utf-8")
    flights = (root / "EllesmereUIForeverEssentials_FlightTimerData.lua").read_text(encoding="utf-8")

    docks = parse_transports(travel)
    links, skipped = [], []
    for src in sorted(docks):
        for x, y, kind, dest in docks[src]:
            arr = arrival(docks, src, x, y, kind, dest)
            if not arr:
                skipped.append(f"{kind} {src} ({x}, {y}) -> {dest}: no dock on the far side")
                continue
            faction = link_faction(kind, src, dest)
            who = f'faction = "{faction}", ' if faction else ""
            links.append(f'    {{ kind = "{kind}", {who}from = {{ map = {src}, x = {x}, y = {y} }}, '
                         f'to = {{ map = {dest}, x = {arr[0]}, y = {arr[1]} }} }},')
    (DATA / "Transports.lua").write_text(
        "-- Boats, zeppelins, skycutters, the Deeprun Tram and the Stormwind portal: one-way links\n"
        "-- from the dock where you board ({ map = uiMapID, x, y } in 0-100) to where you arrive.\n"
        + CREDIT +
        "local _, ns = ...\n\n"
        "ns.Transports = {\n" + "\n".join(links) + "\n}\n\n"
        "-- Rough time per trip in seconds: average wait at the dock plus the ride itself.\n"
        "ns.TRANSPORT_SECONDS = { boat = 240, zeppelin = 240, skycutter = 240, tram = 120, portal = 15 }\n\n"
        "ns.TRANSPORT_NAMES = { boat = \"boat\", zeppelin = \"zeppelin\", skycutter = \"skycutter\",\n"
        "    tram = \"Deeprun Tram\", portal = \"portal\" }\n",
        encoding="utf-8", newline="\n")

    routes = re.findall(r"\[(\d+)\] = (\d+),", flights)
    (DATA / "FlightLengths.lua").write_text(
        "-- Flown length in yards of each flight route on WoW Forever, keyed\n"
        "-- fromTaxiNodeID * 10000 + toTaxiNodeID (direct hops only).\n"
        + CREDIT +
        "local _, ns = ...\n\n"
        "ns.FlightLengths = {\n" + "\n".join(f"    [{k}] = {v}," for k, v in routes) + "\n}\n",
        encoding="utf-8", newline="\n")

    print(f"wrote {len(links)} transport links and {len(routes)} flight routes")
    for s in skipped:
        print("skipped", s)


if __name__ == "__main__":
    main()
